"""Tests for the partial-GLB VRM metadata extractor.

Tests the parsing core (parse_glb, parse_glb_header, extract_vrm_from_gltf)
against synthetic fixture files — no network calls. The HTTP range-request
path (fetch_vrm_meta / get_range) is tested via mock to verify the
range-unsupported fallback behavior.

Fixtures are generated by tests/fixtures/generate_vrm_fixtures.py.
"""

from __future__ import annotations

import json
import struct
import sys
from pathlib import Path
from unittest.mock import patch

import pytest

_REPO_ROOT = Path(__file__).resolve().parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from scripts.extract_vrm_meta import (  # noqa: E402
    GLB_MAGIC,
    GLB_VERSION_2,
    JSON_CHUNK_TYPE,
    extract_vrm_from_gltf,
    fetch_vrm_meta,
    parse_glb,
    parse_glb_header,
    summarize_meta,
)

FIXTURE_DIR = _REPO_ROOT / "tests" / "fixtures" / "vrm"


def _fixture(name: str) -> bytes:
    return (FIXTURE_DIR / name).read_bytes()


# ─── parse_glb_header ──────────────────────────────────────────────────────


def test_header_too_short():
    with pytest.raises(ValueError, match="Header too short"):
        parse_glb_header(b"\x00" * 10)


def test_header_parses_valid_glb():
    data = _fixture("vrm_0x_minimal.glb")
    magic, version, total, jlen, ctype = parse_glb_header(data[:20])
    assert magic == GLB_MAGIC
    assert version == GLB_VERSION_2
    assert ctype == JSON_CHUNK_TYPE
    assert total == len(data)
    assert jlen > 0


