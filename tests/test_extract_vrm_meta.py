def test_parse_wrong_glb_version():
    """Construct a GLB with version 1 instead of 2."""
    json_bytes = json.dumps({"asset": {"version": "2.0"}}).encode()
    while len(json_bytes) % 4:
        json_bytes += b"\x00"
    total = 12 + 8 + len(json_bytes)
    header = struct.pack("<IIIIII", GLB_MAGIC, 1, total, len(json_bytes), JSON_CHUNK_TYPE, 0)
    # Actually GLB header is only 12 bytes, then chunk header is 8 bytes
    header = struct.pack("<III", GLB_MAGIC, 1, total)
    chunk = struct.pack("<II", len(json_bytes), JSON_CHUNK_TYPE) + json_bytes
    with pytest.raises(ValueError, match="Unsupported GLB version"):
        parse_glb(header + chunk)


def test_parse_first_chunk_not_json():
    """Construct a GLB where the first chunk type is BIN, not JSON."""
    json_bytes = b"\x00" * 4
    total = 12 + 8 + len(json_bytes)
    header = struct.pack("<III", GLB_MAGIC, GLB_VERSION_2, total)
    chunk = struct.pack("<II", len(json_bytes), 0x004E4942) + json_bytes  # BIN type
    with pytest.raises(ValueError, match="First chunk is not JSON"):
        parse_glb(header + chunk)


